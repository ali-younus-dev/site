/* ---- LOCAL PREVIEW NAV: lets clean-URL links work when the site is opened directly
   from disk (file://). Does NOTHING on a real web server. Safe on every page. ---- */
(function(){
  if(location.protocol!=='file:') return;
  document.addEventListener('click',function(e){
    var a=e.target.closest&&e.target.closest('a'); if(!a) return;
    var href=a.getAttribute('href');
    if(!href||href.charAt(0)!=='/'||href.charAt(1)==='/') return; // only site-internal /… links
    e.preventDefault();
    var p=href, sfx=''; var qi=href.search(/[?#]/);
    if(qi>=0){ p=href.slice(0,qi); sfx=href.slice(qi); }
    p=p.replace(/^\/+/,'');
    var last=p.substring(p.lastIndexOf('/')+1);
    if(p===''||p.charAt(p.length-1)==='/'){ p+='index.html'; }
    else if(last.indexOf('.')===-1){ p+='/index.html'; }
    location.href=(window.__PBASE||'')+p+sfx;
  },true);
})();


